def _ensure_safe_migrations():
    """Safely ensure new tables and columns exist in SQLite/SQL without touching user data."""
    try:
        Base.metadata.create_all(bind=engine)
        with engine.begin() as conn:
            if engine.dialect.name == "sqlite":
                cols = [row[1] for row in conn.execute(text("PRAGMA table_info(user_profiles)")).fetchall()]
                if cols and "target_weight_kg" not in cols:
                    conn.execute(text("ALTER TABLE user_profiles ADD COLUMN target_weight_kg FLOAT"))
    except Exception:
        pass

